export function withReportVoice(template: string, register: "formal" | "informal"): string {
  const tone = register === "formal"
    ? "호칭과 어미: 따뜻하고 차분한 존댓말을 유지한다. 딱딱한 보고체로 바꾸지 않는다."
    : "호칭과 어미: 차분하고 따뜻한 반말을 유지한다. 훈계·비꼼·과한 친한 척은 하지 않는다. 가족·상대는 존중해서 묘사한다.";
  return `${template}\n\n${REPORT_VOICE_GUIDE}\n${tone}`;
}
